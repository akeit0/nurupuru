import { spawnSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const folder = path.join(root, 'test-results/wasm');
await mkdir(folder, { recursive: true });
const output = path.join(folder, 'physics.wasm');
const args = ['cc', 'src/wasm/physics.c', '-target', 'wasm32-wasi', '-O3', '-ffp-contract=off',
  '-fno-vectorize', '-fno-slp-vectorize', '-mexec-model=reactor', '-Wl,-z,stack-size=65536',
  '-Wl,--initial-memory=131072', '-Wl,--max-memory=33554432', '-Wl,--export=__heap_base', '-Wl,--strip-all', '-o', output];
const result = spawnSync(process.env.ZIG ?? 'zig', args, { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) throw Error(`zig cc failed (${result.status})`);
const bytes = await readFile(output), module = new WebAssembly.Module(bytes);
if (WebAssembly.Module.imports(module).length) throw Error('Physics WASM must be self-contained');
await writeFile(path.join(root, 'src/wasm/physics-binary.js'),
  `// Generated by npm run build:wasm. Source: physics.c (Unlicense).\nexport const scalar = '${bytes.toString('base64')}';\n`);
console.log(`WASM: ${bytes.length.toLocaleString()} bytes`);
